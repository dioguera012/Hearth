type DeepPartial<T> = T extends (...args: never[]) => unknown
	? T
	: T extends readonly unknown[]
		? T
		: T extends object
			? { [K in keyof T]?: DeepPartial<T[K]> }
			: T;

/** Copy `base`, replacing each value that `overrides` provides. */
function merge(base: unknown, overrides: unknown): unknown {
	const isPlain = (v: unknown): v is Record<string, unknown> =>
		typeof v === "object" && v !== null && !Array.isArray(v);
	if (!isPlain(base) || !isPlain(overrides)) return overrides;
	const out: Record<string, unknown> = { ...base };
	for (const [key, value] of Object.entries(overrides)) {
		if (value !== undefined) out[key] = merge(base[key], value);
	}
	return out;
}

function mergeLocale(
	base: Translations,
	overrides: DeepPartial<Translations>,
): Translations {
	return merge(base, overrides) as Translations;
}

